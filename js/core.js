/* ============ 十神 ============ */
/* 以日干(我)为基准，求另一干(他)对日干的作用 */
function shiShen(dayGan, otherGan){
  if (dayGan === otherGan) return '比肩';
  const same = (dayGan % 2) === (otherGan % 2); /* 阴阳是否相同 */
  const my = GAN_WUXING[dayGan], other = GAN_WUXING[otherGan];
  if (my === other) return same ? '比肩' : '劫财';
  if (WUXING_SHENG[my] === other) return same ? '食神' : '伤官';
  if (WUXING_KE[my] === other) return same ? '偏财' : '正财';
  if (WUXING_KE[other] === my) return same ? '七杀' : '正官';
  if (WUXING_SHENG[other] === my) return same ? '偏印' : '正印';
  return '';
}
